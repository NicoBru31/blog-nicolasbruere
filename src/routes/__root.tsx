import { createRootRoute, HeadContent, Link, Scripts, useLocation } from '@tanstack/react-router'
import type { ReactNode } from 'react'
import { CurrentReading } from '#/components/CurrentReading'
import { LanguageSwitch } from '#/components/LanguageSwitch'
import { ThemeToggle, themeInitScript } from '#/components/ThemeToggle'
import { LINKS } from '#/lib/about'
import { rssPath } from '#/lib/feeds'
import { LOCALES, localizedPath, useI18n } from '#/lib/i18n'
import { OG_LOCALES } from '#/lib/seo'
import { absoluteUrl, SITE } from '#/lib/site'
import appCss from '../styles.css?url'

export const Route = createRootRoute({
  head: () => ({
    meta: [
      { charSet: 'utf-8' },
      { name: 'viewport', content: 'width=device-width, initial-scale=1' },
      { title: SITE.title },
      { name: 'theme-color', content: '#faf8f3', media: '(prefers-color-scheme: light)' },
      { name: 'theme-color', content: '#1b1916', media: '(prefers-color-scheme: dark)' },
      // Overridden with `article` by post pages.
      { property: 'og:type', content: 'website' },
    ],
    links: [
      { rel: 'stylesheet', href: appCss },
      // Icons generated by scripts/icons.ts (bun run gen:icons).
      { rel: 'icon', href: '/favicon.ico', sizes: '48x48' },
      { rel: 'icon', href: '/favicon.svg', type: 'image/svg+xml' },
      { rel: 'apple-touch-icon', href: '/apple-touch-icon.png' },
      { rel: 'manifest', href: '/site.webmanifest' },
    ],
  }),
  shellComponent: RootDocument,
  notFoundComponent: NotFound,
})

const X_HANDLE = LINKS.find((link) => link.label === 'x')?.handle ?? ''

const navLink = 'transition-colors hover:text-accent'
const navActive = { className: 'text-ink' }

function RootDocument({ children }: { children: ReactNode }) {
  const { locale, t, param } = useI18n()
  const { pathname } = useLocation()
  const canonical = absoluteUrl(pathname.length > 1 ? pathname.replace(/\/+$/, '') : pathname)

  return (
    <html lang={t.htmlLang} suppressHydrationWarning>
      <head>
        <script dangerouslySetInnerHTML={{ __html: themeInitScript }} />
        {/* The same page in each language, for search engines. */}
        {LOCALES.map((alt) => (
          <link
            key={alt}
            rel="alternate"
            hrefLang={alt}
            href={absoluteUrl(localizedPath(pathname, alt))}
          />
        ))}
        <link
          rel="alternate"
          hrefLang="x-default"
          href={absoluteUrl(localizedPath(pathname, 'en'))}
        />
        {/* Prerendered URLs have no trailing slash: `/posts/x/` redirects to `/posts/x`. */}
        <link rel="canonical" href={canonical} />
        <link
          rel="alternate"
          type="application/rss+xml"
          title={SITE.title}
          href={absoluteUrl(rssPath(locale))}
        />
        <meta property="og:url" content={canonical} />
        <meta property="og:site_name" content={SITE.title} />
        <meta property="og:locale" content={OG_LOCALES[locale]} />
        {LOCALES.filter((alt) => alt !== locale).map((alt) => (
          <meta key={alt} property="og:locale:alternate" content={OG_LOCALES[alt]} />
        ))}
        <meta property="og:image" content={absoluteUrl(SITE.ogImage.path)} />
        <meta property="og:image:width" content={String(SITE.ogImage.width)} />
        <meta property="og:image:height" content={String(SITE.ogImage.height)} />
        <meta property="og:image:alt" content={SITE.title} />
        <meta name="twitter:card" content="summary_large_image" />
        <meta name="twitter:site" content={X_HANDLE} />
        <HeadContent />
      </head>
      <body className="bg-paper font-sans text-ink antialiased">
        {/* Full-height column: <main> grows so the footer sits at the bottom on short pages. */}
        <div className="mx-auto flex min-h-dvh max-w-3xl flex-col px-5 py-8 sm:py-10">
          <header className="mb-14 flex flex-wrap items-center justify-between gap-3 text-sm">
            <Link
              to="/{-$locale}"
              params={{ locale: param }}
              className="font-mono text-[15px] text-heading"
            >
              ~/nicolas<span className="text-accent">.bruere</span>
            </Link>
            <nav className="flex flex-wrap items-center gap-x-4 gap-y-1 font-mono text-muted">
              <Link
                to="/{-$locale}"
                params={{ locale: param }}
                className={navLink}
                activeProps={navActive}
                activeOptions={{ exact: true }}
              >
                {t.nav.articles}
              </Link>
              <Link
                to="/{-$locale}/readings"
                params={{ locale: param }}
                className={navLink}
                activeProps={navActive}
              >
                {t.nav.readings}
              </Link>
              <Link
                to="/{-$locale}/tags"
                params={{ locale: param }}
                className={navLink}
                activeProps={navActive}
              >
                {t.nav.tags}
              </Link>
              <Link
                to="/{-$locale}/about"
                params={{ locale: param }}
                className={navLink}
                activeProps={navActive}
              >
                {t.nav.about}
              </Link>
              <LanguageSwitch />
              <ThemeToggle />
            </nav>
          </header>
          <CurrentReading />
          <main className="flex-1">{children}</main>
          <footer className="mt-24 flex flex-wrap justify-between gap-2 border-t border-line pt-6 font-mono text-xs text-faint">
            <span>© {new Date().getFullYear()} Nicolas Bruère</span>
            <span>{t.footerStack}</span>
          </footer>
        </div>
        <Scripts />
      </body>
    </html>
  )
}

function NotFound() {
  const { t, param } = useI18n()
  return (
    <div className="py-10">
      <p className="font-mono text-sm text-faint">{t.notFound.code}</p>
      <h1 className="mt-2 text-2xl font-medium text-heading">{t.notFound.title}</h1>
      <Link
        to="/{-$locale}"
        params={{ locale: param }}
        className="mt-6 inline-block font-mono text-sm text-accent hover:underline"
      >
        {t.notFound.back}
      </Link>
    </div>
  )
}
